import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { resolve, join } from "node:path";
import { existsSync, mkdtempSync, mkdirSync } from "node:fs";
import { windowsPowerShellEnv, powershellArgs } from "../powershell.mjs";
const args=process.argv.slice(2),index=args.indexOf("--installer");
assert.ok(index>=0 && args[index+1],"Usage: --installer <validation NSIS installer>");
const installer=resolve(args[index+1]);assert.ok(installer.endsWith(".exe") && existsSync(installer));
const metadata=spawnSync("powershell.exe",[...powershellArgs,"-File",resolve("scripts/release/metadata.ps1"),"-Path",installer],{encoding:"utf8",env:windowsPowerShellEnv(),windowsHide:true});
assert.equal(metadata.status,0,metadata.stderr);
const product=JSON.parse(metadata.stdout.replace(/^\uFEFF/,""));
assert.equal(product.productName,"Chatterino RT Validation","Only the isolated validation installer may be installed by this test");
mkdirSync(resolve("artifacts"),{recursive:true});
const directory=mkdtempSync(resolve("artifacts/validation-installed-"));
const installed=spawnSync(installer,["/S",`/D=${directory}`],{stdio:"inherit",windowsHide:true,windowsVerbatimArguments:true,timeout:180000});
assert.equal(installed.status,0,"validation installer failed");
const exe=join(directory,"tauri-app.exe");assert.ok(existsSync(exe),"installed application missing");
const updateIndex=args.indexOf("--update-installer");
const result=spawnSync(process.execPath,[resolve("scripts/desktop/run.mjs"),"--exe",exe,"--output",join(directory,"smoke.json"),...(updateIndex>=0?["--update-installer",args[updateIndex+1]]:[])],{stdio:"inherit",windowsHide:true});
process.exitCode=result.status??1;
